export interface ReferenceHeight {
  /** Hauteur de l'objet, en mm (0 : à plat, rien à dessiner en volume). */
  height: number
  /** Hauteur du dessous au-dessus du sol, en mm, pour un objet fixé en hauteur. */
  elevation?: number
}

/** Hauteur de référence prévue pour cet identifiant, ou `null` s'il n'a pas de règle propre. */
export function explicitReferenceHeight(id: string): ReferenceHeight | null {
  for (const [pattern, height, elevation] of RULES) {
    if (pattern.test(id)) return elevation === undefined ? { height } : { height, elevation }
  }
  return null
}
